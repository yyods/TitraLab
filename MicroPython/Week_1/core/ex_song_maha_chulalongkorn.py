# ex_song_maha_chulalongkorn.py - เพลงมหาจุฬาลงกรณ์ (2 บรรทัดแรก) ด้วย Buzzer
# "Maha Chulalongkorn" anthem (first 2 lines) on the piezo buzzer
# ==============================================================================
# สัปดาห์ที่ 1: ตัวอย่างสนุก ๆ ต่อยอดจาก PWM (Week 1: a fun PWM follow-up)
#
# วัตถุประสงค์การเรียนรู้ (Learning Objectives):
#   1. PWM ไม่ได้มีแค่ duty cycle — "ความถี่" (frequency) คือระดับเสียงดนตรี
#      (PWM frequency IS musical pitch: A4 = 440 Hz)
#   2. แปลงโน้ตเพลงจริงเป็นข้อมูล (ความถี่, จังหวะ) แล้วเล่นด้วยลูปเดียว
#      (Turn real sheet music into (frequency, beats) data + one play loop)
#   3. เพลงคือ "ข้อมูล + เวลา" — แนวคิดเดียวกับการจ่ายไทแทรนต์เป็นจังหวะใน Week 3
#
# ที่มา (Source): โน้ตเพลงมหาจุฬาลงกรณ์ กุญแจซอล บันไดเสียง F เมเจอร์ 4/4
#   (พระราชนิพนธ์ในพระบาทสมเด็จพระบรมชนกาธิเบศร มหาภูมิพลอดุลยเดชมหาราช)
#   บรรทัดที่ 1: "น้ำใจน้องพี่สีชมพู  ทุกคนไม่รู้ลืมบูชา"
#   บรรทัดที่ 2: "พระคุณของแหล่งเรียนมา  จุฬาลงกรณ์"
#
# ฮาร์ดแวร์ (Hardware): Buzzer ที่ GPIO26 (ดู pins.py: BUZZER_PIN)
# ==============================================================================

import time

from machine import Pin, PWM

# ==============================================================================
# ค่าคงที่ (Constants)
# ==============================================================================
MY_BUZZER_PIN = 26        # GPIO26 - Buzzer (PWM) ตามผังบอร์ด TitraLab

# --- ความถี่ของโน้ต (Note frequencies, Hz) — บันไดเสียง F เมเจอร์ ---
# ชื่อโน้ตแบบสากล: ตัวเลขคือ octave (A4 = ลา มาตรฐาน 440 Hz)
D4 = 294   # เร     (D below middle-ish)
F4 = 349   # ฟา
G4 = 392   # ซอล
A4 = 440   # ลา
Bb4 = 466  # ที-แฟลต (คีย์ F เมเจอร์ มี B-flat ตามเครื่องหมายกุญแจ)
C5 = 523   # โด (สูง)
D5 = 587   # เร (สูง)
REST = 0   # เงียบ (rest = no sound)

# --- จังหวะ (Rhythm) ---
TEMPO_BPM = 120           # ความเร็วเพลง (โน้ตดำ = 1 จังหวะ)
BEAT_MS = 60000 // TEMPO_BPM   # 1 จังหวะกี่มิลลิวินาที (ms per quarter-note beat)
GAP_MS = 25               # ช่องว่างสั้น ๆ ระหว่างโน้ต ให้โน้ตซ้ำ (เช่น ลา-ลา) ฟังออก
DUTY_ON = 32768           # duty 50% (duty_u16) = เสียงดังชัด
DUTY_OFF = 0              # เงียบ

# ==============================================================================
# เพลง: (ความถี่, จำนวนจังหวะ) ต่อ 1 พยางค์ — ถอดจากโน้ตจริงทีละตัว
# The melody: one (frequency, beats) pair per syllable, straight off the score.
# เขบ็ตหนึ่งชั้น = 0.5 จังหวะ, โน้ตดำ = 1, ตัวกลม = 4, โยงเสียง = บวกจังหวะรวมกัน
# ==============================================================================
MELODY = [
    # --- บรรทัดที่ 1 วรรคแรก: "น้ำ ใจ น้อง พี่ สี ชม พู" ---
    (REST, 0.5),
    (C5, 0.5),   # น้ำ
    (A4, 0.5),   # ใจ
    (C5, 0.5),   # น้อง
    (F4, 0.5),   # พี่
    (D5, 0.5),   # สี
    (C5, 0.5),   # ชม
    (A4, 4.5),   # พู—— (เขบ็ตโยงเสียงเข้าตัวกลม = 0.5 + 4 จังหวะ)

    # --- บรรทัดที่ 1 วรรคหลัง: "ทุก คน ไม่ รู้ ลืม บู ชา" ---
    (REST, 0.5),
    (D5, 0.5),   # ทุก
    (C5, 0.5),   # คน
    (F4, 0.5),   # ไม่
    (Bb4, 0.5),  # รู้
    (A4, 0.5),   # ลืม
    (F4, 0.5),   # บู
    (G4, 4.5),   # ชา——

    # --- บรรทัดที่ 2 วรรคแรก: "พระ คุณ ของ แหล่ง เรียน มา" ---
    (REST, 0.5),
    (A4, 0.5),   # พระ
    (G4, 0.5),   # คุณ
    (A4, 0.5),   # ของ
    (D4, 1.0),   # แหล่ง (โน้ตดำ เสียงต่ำ)
    (F4, 1.0),   # เรียน (โน้ตดำ)
    (A4, 4.0),   # มา—— (ตัวกลม)

    # --- บรรทัดที่ 2 วรรคหลัง: "จุ ฬา ลง กรณ์" ---
    (REST, 1.0),
    (F4, 1.0),   # จุ  (โน้ตดำ)
    (A4, 1.0),   # ฬา (โน้ตดำ)
    (A4, 0.5),   # ลง
    (C5, 4.5),   # กรณ์—— (เขบ็ตโยงเสียงเข้าตัวกลม)
]

# ==============================================================================
# ฟังก์ชันเล่นเพลง (Play function)
# ==============================================================================


def play_song(melody):
    """เล่นรายการโน้ต (ความถี่ Hz, จังหวะ beat) ทีละตัวด้วย PWM

    หลักการ: ตั้ง freq = ระดับเสียง แล้วเปิด duty เมื่อถึงเวลาโน้ตถัดไปก็เปลี่ยน
    freq ใหม่ ปิด duty ช่วงสั้น ๆ ระหว่างโน้ตเพื่อให้โน้ตซ้ำกันฟังเป็นคนละตัว
    """
    # สร้าง PWM แล้ว "ปิดเสียงทันที" — ESP32 เริ่ม PWM แบบมีเสียงตั้งแต่สร้าง
    # (create silent FIRST: ESP32 PWM is audible at construction by default)
    buzzer = PWM(Pin(MY_BUZZER_PIN))
    buzzer.duty_u16(DUTY_OFF)

    try:
        for freq, beats in melody:
            note_ms = int(beats * BEAT_MS)
            if freq == REST:
                buzzer.duty_u16(DUTY_OFF)
                time.sleep_ms(note_ms)
                continue
            buzzer.freq(freq)
            buzzer.duty_u16(DUTY_ON)
            time.sleep_ms(note_ms - GAP_MS)
            buzzer.duty_u16(DUTY_OFF)     # ช่องว่างให้โน้ตขาดจากกัน (articulation)
            time.sleep_ms(GAP_MS)
    finally:
        # ปิดเสียงเสมอ แม้กด Ctrl+C กลางเพลง (always silence, even on Ctrl+C)
        buzzer.duty_u16(DUTY_OFF)
        buzzer.deinit()


# ==============================================================================
# โปรแกรมหลัก (Main)
# ==============================================================================
print("=" * 56)
print("เพลงมหาจุฬาลงกรณ์ (Maha Chulalongkorn) - 2 บรรทัดแรก")
print("=" * 56)
print(f"Tempo: {TEMPO_BPM} BPM | Buzzer: GPIO{MY_BUZZER_PIN}")
print("'น้ำใจน้องพี่สีชมพู ทุกคนไม่รู้ลืมบูชา")
print(" พระคุณของแหล่งเรียนมา จุฬาลงกรณ์'")
print("")

play_song(MELODY)

print("จบเพลง (Song finished)")
print("ลองปรับ TEMPO_BPM หรือแต่งท่อนต่อไปเองดูสิ!")
print("(Try changing TEMPO_BPM, or transcribe the next lines yourself!)")
